#!/usr/bin/env python3
"""Extract and pack the original WL1 status-bar art for the Agon port.

Inputs are the bundled ``VGADICT.WL1``, ``VGAHEAD.WL1``, and
``VGAGRAPH.WL1`` files.  Outputs are source/converted PNGs, RGBA2222 payloads,
a JSONL audit manifest, a generated eZ80 constants include, and ``hud.agnb``.

Stable VDP contract:

* each original picture chunk uses buffer ``0x4000 + chunkId``;
* the composed 320x80 mode-8 panel uses buffer ``0x40F0``;
* chunk 98 is preserved separately as well as forming rows 0..39 of the
  composed panel;
* chunks 103..144 provide weapons, key icons, digits, and face frames.

The composite panel's first 40 source rows and first 40 converted RGBA2222
rows are verified byte-for-byte against chunk 98.  Its lower 40 rows are a
neutral continuation of the original blue/cyan frame style and deliberately
contain no duplicated labels or value slots.

The intended mode-8 composition is a 256x160 raycast viewport at x=32,y=0,
then this 320x80 panel at x=0,y=160: original strip on screen rows 160..199,
deliberate neutral fill on rows 200..239.  Splash/title art is out of scope.
"""

from __future__ import annotations

import argparse
import json
import shutil
import sys
from dataclasses import asdict, dataclass
from pathlib import Path

import agonutils as au
from PIL import Image, ImageDraw

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from agnb.container import BufferRecord, build_container  # noqa: E402
from formats.hud import (  # noqa: E402
    HUD_CHUNKS,
    HUD_CHUNK_BUFFER_BASE,
    HUD_CHUNK_NAMES,
    HUD_EXPECTED_DIMENSIONS,
    STATUS_PANEL_BUFFER_ID,
    STATUS_PANEL_HEIGHT,
    STATUS_PANEL_WIDTH,
    STATUSBAR_CHUNK,
    chunk_buffer_id,
)
from formats.vgagraph import read_vgagraph  # noqa: E402

SCRIPT_FILE = Path(__file__).resolve()
TOOLS_ROOT = SCRIPT_FILE.parents[1]
PROJECT_ROOT = next(
    (
        parent
        for parent in SCRIPT_FILE.parents
        if (parent / "orig" / "data" / "VGAGRAPH.WL1").is_file()
    ),
    Path.cwd(),
)
DEFAULT_DATA_DIR = PROJECT_ROOT / "orig" / "data"
DEFAULT_OUT_DIR = PROJECT_ROOT / "agonport" / "assets" / "generated" / "wolf3d" / "hud"
DEFAULT_PALETTE_FILE = TOOLS_ROOT / "palettes" / "Agon64.gpl"
IMAGE_FORMAT_RGBA2222 = 1

# Original Wolf palette indices already used by STATUSBARPIC.  The extension
# repeats only its neutral material and bevel language, never its labels or
# data slots.
PANEL_SURROUND = 127
PANEL_SHADOW = 0
PANEL_HIGHLIGHT = 139
PANEL_MID = 151
PANEL_LOWLIGHT = 155
PANEL_DARK = 159


@dataclass(frozen=True)
class HudManifestEntry:
    name: str
    source: str
    chunkId: int | None
    bufferId: int
    width: int
    height: int
    format: int
    png: str
    rgba2: str
    dataSize: int


def make_status_panel(statusbar: Image.Image) -> Image.Image:
    """Return an indexed 320x80 panel with STATUSBARPIC in its first half."""
    if statusbar.mode != "P" or statusbar.size != (STATUS_PANEL_WIDTH, 40):
        raise ValueError(
            f"STATUSBARPIC must be a 320x40 paletted image, got "
            f"{statusbar.mode} {statusbar.size}"
        )

    panel = Image.new("P", (STATUS_PANEL_WIDTH, STATUS_PANEL_HEIGHT), PANEL_SURROUND)
    panel.putpalette(statusbar.getpalette())
    panel.paste(statusbar, (0, 0))

    draw = ImageDraw.Draw(panel)
    # A full-width material band avoids inventing another labeled/value slot.
    # The narrow horizontal bevels echo the original panel without implying
    # any new semantic regions.
    draw.rectangle((0, 40, 319, 79), fill=PANEL_MID)
    draw.line((0, 40, 319, 40), fill=PANEL_SURROUND)
    draw.line((0, 41, 319, 41), fill=PANEL_SHADOW)
    draw.line((0, 42, 319, 42), fill=PANEL_HIGHLIGHT)
    draw.line((0, 59, 319, 59), fill=PANEL_LOWLIGHT)
    draw.line((0, 60, 319, 60), fill=PANEL_DARK)
    draw.line((0, 76, 319, 76), fill=PANEL_LOWLIGHT)
    draw.line((0, 77, 319, 77), fill=PANEL_DARK)
    draw.line((0, 78, 319, 78), fill=PANEL_SHADOW)
    draw.line((0, 79, 319, 79), fill=PANEL_SURROUND)

    if panel.crop((0, 0, STATUS_PANEL_WIDTH, 40)).tobytes() != statusbar.tobytes():
        raise AssertionError("Composed panel changed STATUSBARPIC source pixels")
    return panel


def convert_to_rgba2222(
    source_png: Path,
    processed_png: Path,
    rgba2_file: Path,
    palette_file: Path,
    method: str,
) -> None:
    """Apply the project's established agonutils/Agon64 conversion path."""
    shutil.copy2(source_png, processed_png)
    au.convert_to_palette(
        str(processed_png), str(processed_png), str(palette_file), method, None
    )
    au.img_to_rgba2(
        str(processed_png), str(rgba2_file), str(palette_file), method, None
    )


def _write_constants(path: Path, entries: list[HudManifestEntry]) -> None:
    lines = [
        "; Generated by scripts/build_hud_assets.py -- do not edit.\n",
        "; Original chunk assets: bufferId = $4000 + chunkId.\n",
        f"W3D_HUD_CHUNK_BUFFER_BASE equ ${HUD_CHUNK_BUFFER_BASE:04X}\n",
        f"W3D_HUD_STATUS_PANEL_BUFFER equ ${STATUS_PANEL_BUFFER_ID:04X}\n",
        f"W3D_HUD_STATUS_PANEL_WIDTH equ {STATUS_PANEL_WIDTH}\n",
        f"W3D_HUD_STATUS_PANEL_HEIGHT equ {STATUS_PANEL_HEIGHT}\n",
        "\n",
    ]
    for entry in entries:
        if entry.chunkId is None:
            continue
        symbol = f"W3D_HUD_{entry.name.upper()}_BUFFER"
        lines.append(f"{symbol} equ ${entry.bufferId:04X} ; chunk {entry.chunkId}\n")
    path.write_text("".join(lines))


def build_hud_assets(
    data_dir: Path,
    out_dir: Path,
    palette_file: Path,
    method: str = "floyd",
) -> list[HudManifestEntry]:
    """Build all staged HUD artifacts and return their manifest entries."""
    archive = read_vgagraph(
        data_dir / "VGADICT.WL1",
        data_dir / "VGAHEAD.WL1",
        data_dir / "VGAGRAPH.WL1",
    )
    original_dir = out_dir / "orig"
    processed_dir = out_dir / "processed"
    for generated_dir in (original_dir, processed_dir):
        if generated_dir.exists():
            shutil.rmtree(generated_dir)
        generated_dir.mkdir(parents=True)
    out_dir.mkdir(parents=True, exist_ok=True)

    source_images: list[tuple[str, str, int | None, int, Image.Image]] = []
    statusbar: Image.Image | None = None
    for chunk_id in HUD_CHUNKS:
        image = archive.decode_picture(chunk_id)
        expected = HUD_EXPECTED_DIMENSIONS[chunk_id]
        if image.size != expected:
            raise ValueError(
                f"Chunk {chunk_id} dimensions changed: {image.size}, expected {expected}"
            )
        name = HUD_CHUNK_NAMES[chunk_id]
        source_images.append(
            (name, f"VGAGRAPH.WL1 chunk {chunk_id}", chunk_id, chunk_buffer_id(chunk_id), image)
        )
        if chunk_id == STATUSBAR_CHUNK:
            statusbar = image

    if statusbar is None:
        raise AssertionError("HUD chunk set omitted STATUSBARPIC")
    source_images.append(
        (
            "status_panel",
            "composite: chunk 98 plus neutral mode-8 extension",
            None,
            STATUS_PANEL_BUFFER_ID,
            make_status_panel(statusbar),
        )
    )

    entries: list[HudManifestEntry] = []
    records: list[BufferRecord] = []
    rgba_by_name: dict[str, bytes] = {}
    for name, source, chunk_id, buffer_id, image in source_images:
        source_png = original_dir / f"{name}.png"
        processed_png = processed_dir / f"{name}.png"
        rgba2_file = processed_dir / f"{name}.rgba2"
        image.save(source_png, "PNG")
        convert_to_rgba2222(source_png, processed_png, rgba2_file, palette_file, method)

        width, height = image.size
        rgba2 = rgba2_file.read_bytes()
        if len(rgba2) != width * height:
            raise ValueError(
                f"RGBA2222 size for {name} is {len(rgba2)}, expected {width * height}"
            )
        rgba_by_name[name] = rgba2
        entry = HudManifestEntry(
            name=name,
            source=source,
            chunkId=chunk_id,
            bufferId=buffer_id,
            width=width,
            height=height,
            format=IMAGE_FORMAT_RGBA2222,
            png=str(processed_png.relative_to(out_dir)),
            rgba2=str(rgba2_file.relative_to(out_dir)),
            dataSize=len(rgba2),
        )
        entries.append(entry)
        records.append(
            BufferRecord(
                name=name,
                bufferId=buffer_id,
                width=width,
                height=height,
                rgba2File=rgba2_file,
                dataSize=len(rgba2),
            )
        )

    statusbar_rgba = rgba_by_name[HUD_CHUNK_NAMES[STATUSBAR_CHUNK]]
    panel_rgba = rgba_by_name["status_panel"]
    if panel_rgba[: STATUS_PANEL_WIDTH * 40] != statusbar_rgba:
        raise AssertionError("Converted status panel changed STATUSBARPIC's top 40 rows")

    manifest_path = out_dir / "hud_assets.jsonl"
    manifest_path.write_text(
        "".join(json.dumps(asdict(entry), sort_keys=True) + "\n" for entry in entries)
    )
    (out_dir / "hud.agnb").write_bytes(build_container(records))
    _write_constants(out_dir / "hud_buffers.inc", entries)
    return entries


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--data-dir", type=Path, default=DEFAULT_DATA_DIR)
    parser.add_argument("--out-dir", type=Path, default=DEFAULT_OUT_DIR)
    parser.add_argument("--palette", type=Path, default=DEFAULT_PALETTE_FILE)
    parser.add_argument(
        "--method",
        default="floyd",
        choices=("rgb", "hsv", "bayer", "floyd", "atkinson"),
        help="agonutils palette-conversion method (default: floyd)",
    )
    args = parser.parse_args()

    entries = build_hud_assets(args.data_dir, args.out_dir, args.palette, args.method)
    total_pixels = sum(entry.dataSize for entry in entries)
    print(
        f"Wrote {args.out_dir / 'hud.agnb'}: {len(entries)} images, "
        f"{total_pixels} RGBA2222 bytes"
    )
    print(
        f"Original chunks: {STATUSBAR_CHUNK}, 103..144 at "
        f"${HUD_CHUNK_BUFFER_BASE:04X}+chunk; panel: ${STATUS_PANEL_BUFFER_ID:04X}"
    )


if __name__ == "__main__":
    main()
