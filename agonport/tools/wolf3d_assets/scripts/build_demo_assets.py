#!/usr/bin/env python3
"""Extract the canonical WL1 demo streams and emit their assembly include."""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import sys


TOOLS_ROOT = Path(__file__).resolve().parents[1]
REPO_ROOT = Path(__file__).resolve().parents[4]
sys.path.insert(0, str(TOOLS_ROOT))

from formats.demo import DEMO_HEADER_SIZE, find_recorded_demos
from formats.vgagraph import read_vgagraph


DEFAULT_DATA = REPO_ROOT / "orig/data"
DEFAULT_OUTPUT = REPO_ROOT / "agonport/assets/generated/wolf3d/demos"
DEFAULT_INCLUDE = REPO_ROOT / "src/asm/wolf3d/src/wolf3d_demo_assets.inc"


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def emit_bytes(data: bytes) -> list[str]:
    return [
        "    db " + ",".join(f"0{value:02x}h" for value in data[index:index + 16])
        for index in range(0, len(data), 16)
    ]


def build_assets(data_root: Path = DEFAULT_DATA) -> tuple[str, dict[str, object]]:
    dictionary = data_root / "VGADICT.WL1"
    head = data_root / "VGAHEAD.WL1"
    graph = data_root / "VGAGRAPH.WL1"
    archive = read_vgagraph(dictionary, head, graph)
    demos = find_recorded_demos(archive)

    lines = [
        "; Generated by build_demo_assets.py from the canonical WL1 archive.",
        "; Each stream retains its four-byte original header and three-byte records.",
        "W3D_DEMO_COUNT: equ 4",
        "W3D_DEMO_HEADER_SIZE: equ 4",
        "W3D_DEMO_RECORD_SIZE: equ 3",
        "",
        "w3d_demo_stream_table:",
    ]
    for index in range(len(demos)):
        lines.append(f"    dl w3d_demo_stream_{index}")
        lines.append(f"    dl w3d_demo_stream_{index}_end")
    lines.append("")
    for index, demo in enumerate(demos):
        lines.append(f"w3d_demo_stream_{index}:")
        lines.extend(emit_bytes(demo.expanded))
        lines.append(f"w3d_demo_stream_{index}_end:")
        lines.append("")

    manifest: dict[str, object] = {
        "schemaVersion": 1,
        "sourceFiles": {
            name: {
                "path": f"orig/data/{path.name}",
                "sha256": sha256(path.read_bytes()),
            }
            for name, path in (
                ("dictionary", dictionary),
                ("head", head),
                ("graph", graph),
            )
        },
        "headerBytes": DEMO_HEADER_SIZE,
        "recordBytes": 3,
        "recordTics70Hz": 4,
        "demos": [
            {
                "index": index,
                "chunkId": demo.chunk_id,
                "mapIndex": demo.map_index,
                "displayFloor": demo.map_index + 1,
                "bytes": len(demo.expanded),
                "records": demo.record_count,
                "reservedHeaderByte": demo.reserved,
                "sha256": sha256(demo.expanded),
            }
            for index, demo in enumerate(demos)
        ],
    }
    return "\n".join(lines), manifest


def write_assets(output: Path, include: Path, text: str, manifest: dict[str, object]) -> None:
    output.mkdir(parents=True, exist_ok=True)
    include.parent.mkdir(parents=True, exist_ok=True)
    include.write_text(text)
    (output / "demo_manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--data-root", type=Path, default=DEFAULT_DATA)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--include", type=Path, default=DEFAULT_INCLUDE)
    args = parser.parse_args()
    text, manifest = build_assets(args.data_root)
    write_assets(args.output, args.include, text, manifest)
    print(json.dumps(manifest, indent=2))


if __name__ == "__main__":
    main()
