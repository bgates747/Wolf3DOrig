#!/usr/bin/env python3
"""Extract the canonical WL1 IMF streams into a generated assembly include."""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import sys


SCRIPT_DIR = Path(__file__).resolve().parent
REPO_ROOT = SCRIPT_DIR.parents[3]
sys.path.insert(0, str(REPO_ROOT))

from agonport.tools.wolf3d_assets.formats.music import (  # noqa: E402
    EPISODE_ONE_FLOOR_MUSIC,
    MUSIC_NAMES,
    REQUIRED_MUSIC_IDS,
    SHELL_MUSIC,
    read_music_tracks,
)


DEFAULT_AUDIOHED = REPO_ROOT / "orig/data/AUDIOHED.WL1"
DEFAULT_AUDIOT = REPO_ROOT / "orig/data/AUDIOT.WL1"
DEFAULT_INCLUDE = REPO_ROOT / "src/asm/wolf3d/src/wolf3d_music_assets.inc"
DEFAULT_MANIFEST = REPO_ROOT / "agonport/assets/generated/wolf3d/music/music_manifest.json"


def _sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def render_include(tracks) -> str:
    lines = [
        "; Generated by build_music_assets.py; do not hand-edit.",
        "; Canonical WL1 IMF register streams retimed cumulatively from 700 to 120 Hz.",
        "",
        f"W3D_MUSIC_COUNT: equ {len(MUSIC_NAMES)}",
    ]
    for index, name in enumerate(MUSIC_NAMES):
        lines.append(f"W3D_MUSIC_{name}: equ {index}")
    lines.extend(
        [
            "",
            "w3d_music_track_table:",
        ]
    )
    for track in tracks:
        pointer = f"w3d_music_track_{track.name.lower()}" if track.available else "0"
        lines.append(f"    dl {pointer}")
    lines.append("")
    for track in tracks:
        if not track.available:
            continue
        lines.extend(
            [
                f"w3d_music_track_{track.name.lower()}:",
                f"    dw {len(track.events)}",
                f"    dw {track.loop_ticks_120hz}",
            ]
        )
        for event in track.events:
            lines.append(f"    db {event.register},{event.value}")
            lines.append(f"    dw {event.delay_120hz}")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def build(audiohed_path: Path, audiot_path: Path, include_path: Path, manifest_path: Path) -> dict:
    audiohed = audiohed_path.read_bytes()
    audiot = audiot_path.read_bytes()
    tracks = read_music_tracks(audiohed, audiot)
    include = render_include(tracks)
    include_path.parent.mkdir(parents=True, exist_ok=True)
    include_path.write_text(include)
    manifest = {
        "schema": 1,
        "source": {
            "audiohed": {"path": "orig/data/AUDIOHED.WL1", "sha256": _sha256(audiohed)},
            "audiot": {"path": "orig/data/AUDIOT.WL1", "sha256": _sha256(audiot)},
        },
        "timing": {"source_hz": 700, "target_hz": 120, "rounding": "cumulative-nearest"},
        "required_music_ids": list(REQUIRED_MUSIC_IDS),
        "episode_one_floor_music": list(EPISODE_ONE_FLOOR_MUSIC),
        "shell_music": SHELL_MUSIC,
        "tracks": [
            {
                "music_id": track.music_id,
                "name": track.name,
                "chunk_index": track.chunk_index,
                "available": track.available,
                "source_chunk_bytes": len(track.source_bytes),
                "source_sha256": _sha256(track.source_bytes),
                "event_count": len(track.events),
                "source_ticks_700hz": track.source_ticks,
                "loop_ticks_120hz": track.loop_ticks_120hz,
            }
            for track in tracks
        ],
        "generated_include": {
            "path": "src/asm/wolf3d/src/wolf3d_music_assets.inc",
            "bytes": len(include.encode()),
            "sha256": _sha256(include.encode()),
        },
    }
    manifest_path.parent.mkdir(parents=True, exist_ok=True)
    manifest_path.write_text(json.dumps(manifest, indent=2, sort_keys=True) + "\n")
    return manifest


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--audiohed", type=Path, default=DEFAULT_AUDIOHED)
    parser.add_argument("--audiot", type=Path, default=DEFAULT_AUDIOT)
    parser.add_argument("--include", type=Path, default=DEFAULT_INCLUDE)
    parser.add_argument("--manifest", type=Path, default=DEFAULT_MANIFEST)
    args = parser.parse_args()
    manifest = build(args.audiohed, args.audiot, args.include, args.manifest)
    print(json.dumps(manifest["generated_include"], sort_keys=True))


if __name__ == "__main__":
    main()
