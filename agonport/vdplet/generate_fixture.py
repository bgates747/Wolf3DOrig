#!/usr/bin/env python3
"""Generate deterministic Wolf VDPlet tables and bounded-scene inputs."""

from __future__ import annotations

import argparse
import math
from pathlib import Path
import struct


HERE = Path(__file__).resolve().parent
CONFIG_MAGIC = 0x50443357
WORKSPACE_ID = 0x7100
MAP_ID = 0x7101
TEXTURE_ID = 0x7102
ARGUMENT_ID = 0x7103
WORKSPACE_BYTES = 92160


def lround(value: float) -> int:
    return math.floor(value + 0.5) if value >= 0 else math.ceil(value - 0.5)


def format_array(name: str, ctype: str, values: list[int], per_line: int) -> str:
    lines = []
    for start in range(0, len(values), per_line):
        lines.append("    " + ", ".join(str(value) for value in values[start:start + per_line]))
    return (
        f"static const {ctype} {name}[{len(values)}] "
        "__attribute__((aligned(4))) = {\n"
        + ",\n".join(lines)
        + "\n};\n"
    )


def generate_tables(path: Path) -> None:
    sine = [lround(math.sin(index * 2.0 * math.pi / 3600.0) * 65536.0)
            for index in range(901)]
    scale = (128 * (0x5700 + 0x5800)) // 65536
    center = 127
    pixel_angles = [
        lround(math.atan2(center - column, scale) * 3600.0 / (2.0 * math.pi))
        for column in range(256)
    ]
    text = (
        "// Generated by generate_fixture.py; do not hand-edit.\n"
        "#include <stdint.h>\n\n"
        + format_array("kWolfSinQuarter", "int32_t", sine, 8)
        + "\n"
        + format_array("kWolfPixelAngleFine", "int16_t", pixel_angles, 12)
    )
    path.write_text(text)


def generate_map() -> bytes:
    data = bytearray(64 * 64)
    for coordinate in range(64):
        data[coordinate] = 1
        data[63 * 64 + coordinate] = 1
        data[coordinate * 64] = 1
        data[coordinate * 64 + 63] = 1
    # A stepped chamber gives the 256 DDA rays nonuniform depths while the
    # central billboard remains visible in front of the far wall.
    for y in range(1, 13):
        data[y * 64 + 10] = 1
    for x in range(8, 11):
        data[2 * 64 + x] = 1
        data[7 * 64 + x] = 1
    data[3 * 64 + 8] = 1
    data[6 * 64 + 9] = 1
    return bytes(data)


def rgba2222(red: int, green: int, blue: int, alpha: int = 3) -> int:
    return ((alpha & 3) << 6) | ((blue & 3) << 4) | ((green & 3) << 2) | (red & 3)


def generate_textures() -> bytes:
    wall = bytearray(64 * 64)
    sprite = bytearray(64 * 64)
    for y in range(64):
        for x in range(64):
            mortar = (y % 16 == 0) or (x % 16 == (8 if (y // 16) & 1 else 0))
            if mortar:
                wall[y * 64 + x] = rgba2222(1, 1, 1)
            else:
                wall[y * 64 + x] = rgba2222(3, 1 + ((x // 8) & 1), 0)

            dx = x - 31
            dy = y - 31
            body = (dx * dx + dy * dy <= 26 * 26)
            cutout = abs(dx) > 18 and abs(dy) > 18
            eyes = (20 <= y <= 27) and (18 <= x <= 25 or 38 <= x <= 45)
            mouth = 42 <= y <= 46 and 20 <= x <= 43
            if body and not cutout:
                color = rgba2222(3, 3, 0)
                if eyes:
                    color = rgba2222(0, 0, 0)
                elif mouth:
                    color = rgba2222(3, 0, 0)
                sprite[y * 64 + x] = color
    return bytes(wall + sprite)


def generate_config() -> bytes:
    return struct.pack(
        "<IHHHhiiBBH",
        CONFIG_MAGIC,
        WORKSPACE_ID,
        MAP_ID,
        TEXTURE_ID,
        0,              # facing east
        3 * 65536 + 32768,
        4 * 65536 + 32768,
        7, 4, 0,
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--tables", type=Path, default=HERE / "wolf3d_tables.inc")
    parser.add_argument("--output", type=Path, default=HERE / "qualification/build/fixture")
    args = parser.parse_args()
    args.output.mkdir(parents=True, exist_ok=True)
    generate_tables(args.tables)
    (args.output / "map.bin").write_bytes(generate_map())
    (args.output / "textures.bin").write_bytes(generate_textures())
    (args.output / "config.bin").write_bytes(generate_config())
    (args.output / "workspace.bin").write_bytes(bytes(WORKSPACE_BYTES))
    print(f"generated tables and scene fixture in {args.output}")


if __name__ == "__main__":
    main()
