#!/usr/bin/env python3
"""Generate 30 Hz Wolf3D player-motion deltas for the eZ80 fixture.

Each table entry is a signed 24-bit 16.16 delta pair (dx, dy) for one
integer-degree heading. Wolf3D headings are 0=east, 90=north while map Y
increases south, hence dx=cos(angle)*step and dy=-sin(angle)*step.

The generated lookup keeps multiplication and trigonometry out of the
interactive fixture's fixed-step loop.
"""

import argparse
import math
from pathlib import Path

DEFAULT_STEP = 0x1000  # 1/16 tile per 30 Hz quantum = 1.875 tiles/second


def signed24_bytes(value: int) -> tuple[int, int, int]:
    if not -(1 << 23) <= value < (1 << 23):
        raise ValueError(f"{value} does not fit signed 24-bit")
    encoded = value & 0xFFFFFF
    return encoded & 0xFF, (encoded >> 8) & 0xFF, (encoded >> 16) & 0xFF


def build_table(step: int) -> list[tuple[int, int]]:
    entries = []
    for angle in range(360):
        radians = math.radians(angle)
        dx = round(math.cos(radians) * step)
        dy = round(-math.sin(radians) * step)
        entries.append((dx, dy))

    expected = {
        0: (step, 0),
        90: (0, -step),
        180: (-step, 0),
        270: (0, step),
    }
    for angle, value in expected.items():
        if entries[angle] != value:
            raise AssertionError(f"cardinal {angle}: {entries[angle]} != {value}")
    return entries


def emit(out_path: Path, step: int) -> None:
    entries = build_table(step)
    lines = [
        "; Auto-generated by gen_motion_table.py -- do not hand-edit.",
        f"; 360 signed 24-bit (dx,dy) entries; 16.16 step = 0x{step:04X}.",
        "; Heading convention: 0=east, 90=north, map +Y=south.",
        "",
        "w3d_motion_delta_table:",
    ]
    for angle, (dx, dy) in enumerate(entries):
        raw = signed24_bytes(dx) + signed24_bytes(dy)
        lines.append(
            "    db " + ",".join(str(byte) for byte in raw)
            + f" ; {angle:3d} deg: dx={dx:+d}, dy={dy:+d}"
        )
    lines.extend(("w3d_motion_delta_table_end:", ""))
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text("\n".join(lines))


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--step", type=lambda value: int(value, 0), default=DEFAULT_STEP)
    parser.add_argument(
        "--out",
        type=Path,
        default=Path(__file__).resolve().parents[1] / "src" / "wolf3d_motion_table.inc",
    )
    args = parser.parse_args()
    if not 1 <= args.step < (1 << 23):
        parser.error("--step must fit a positive signed 24-bit value")
    emit(args.out, args.step)
    print(f"Wrote {args.out}: 360 headings, 16.16 step 0x{args.step:04X}")


if __name__ == "__main__":
    main()
