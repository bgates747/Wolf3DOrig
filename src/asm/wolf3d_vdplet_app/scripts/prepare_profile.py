#!/usr/bin/env python3
"""Prepare the stopped, hash-pinned Oryx full-game VDPlet profile."""

from __future__ import annotations

import argparse
import hashlib
import importlib.util
import json
import os
from pathlib import Path
import shutil
import subprocess


HOME = Path.home()
PROJECT = HOME / "Agon/mystuff/Wolf3dOrig"
DEFAULT_PROFILE = PROJECT / ".emulator/wolf3d-vdplet-app"
DEFAULT_PACKAGE = PROJECT / "src/asm/wolf3d_vdplet_app/tgt/package"
CANONICAL = HOME / "Agon/mystuff/agon-dev-env/scripts/setup_emulator.py"
FAB_RUNTIME = HOME / "Agon/mystuff/golem/.emulator/runtime/fab-1.2.5"
FLEXE_FRONTEND = (
    HOME / "Agon/mystuff/golem/docs/tasks/GOLEM-037/binding/build/runtime/"
    "flexe-agon-emulator"
)
DEFAULT_FRONTEND_SHA256 = (
    "28f50e87190f00de4039dc90c94432347f01c4771c4ea4a5dea8595d6cef7670"
)
FIRMWARE = HOME / "Agon/mystuff/agon-vdplet/build/vdpl-012/rows-r1/firmware.bin"
FIRMWARE_ELF = HOME / "Agon/mystuff/agon-vdplet/build/vdpl-012/rows-r1/firmware.elf"
BACKEND = (
    HOME / "Agon/mystuff/flexe-agon-emulator/build/fx072/maintained-r02/"
    "flexe-vdp-maintained.so"
)

PINS = {
    "firmware.bin": "8d980025f891484cf7e6cc5f2992cf517cb80e0123ff7de712ae8d7f2dc1c807",
    "firmware.elf": "1a7c44482d4ba8c5bfb49976c0bd664b9a9c2a635c7027b30954929ca567f814",
    "flexe-vdp.so": "0866265bd6f3d73ad572f31dc1bb954f308ed9a5d857efa9414d37e1ade13374",
    "wolf3d.vdpl": "266f809ff76e56733251da202e5c4747cd9c12d247d799d486471a262c0404b7",
}


def sha(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def verify(path: Path, expected: str) -> None:
    actual = sha(path)
    if actual != expected:
        raise SystemExit(f"pin mismatch for {path}: {actual} != {expected}")


def load_canonical():
    spec = importlib.util.spec_from_file_location("agon_emulator_setup", CANONICAL)
    module = importlib.util.module_from_spec(spec)
    assert spec.loader is not None
    spec.loader.exec_module(module)
    return module


def ensure_stopped(profile: Path) -> None:
    marker = str(profile / "sdcard").encode()
    for process in Path("/proc").glob("[0-9]*"):
        try:
            if marker in (process / "cmdline").read_bytes().split(b"\0"):
                raise SystemExit(f"profile is running as PID {process.name}")
        except OSError:
            continue


def retire_verified_profile_identity(profile: Path) -> None:
    """Verify, then retire only generated identity files from a prior stage."""
    pin = profile / ".runtime.sha256"
    if not pin.is_file():
        return
    for line in pin.read_text().splitlines():
        expected, name = line.split("  ", 1)
        verify(profile / name, expected)

    launcher = profile / "flexe-agon-emulator"
    raw = profile / "flexe-agon-emulator.bin"
    marker = "# Generated by agon-dev-env setup_emulator.py."
    if launcher.is_symlink() or not launcher.is_file() or marker not in launcher.read_text():
        raise SystemExit(f"refusing non-generated existing launcher: {launcher}")
    if not raw.is_symlink():
        raise SystemExit(f"refusing non-symlink existing runtime: {raw}")
    launcher.unlink()
    raw.unlink()
    pin.unlink()


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--package", type=Path, default=DEFAULT_PACKAGE)
    parser.add_argument("--profile", type=Path, default=DEFAULT_PROFILE)
    parser.add_argument("--frontend", type=Path, default=FLEXE_FRONTEND)
    parser.add_argument(
        "--frontend-sha256", default=DEFAULT_FRONTEND_SHA256,
        help="required SHA-256 identity of the selected host frontend",
    )
    parser.add_argument(
        "--observer-output", type=Path,
        help="fresh absolute FX-114 JSONL output path; enables observation",
    )
    args = parser.parse_args()
    package = args.package.resolve()
    profile = args.profile.resolve()
    frontend = args.frontend.resolve()
    observer_output = args.observer_output
    if observer_output is not None:
        if not observer_output.is_absolute():
            raise SystemExit("observer output must be an absolute path")
        observer_output = observer_output.resolve()
        if profile == DEFAULT_PROFILE.resolve():
            raise SystemExit("observer output requires a separate diagnostic profile")
        if not observer_output.parent.is_dir():
            raise SystemExit(f"observer output parent is absent: {observer_output.parent}")
        if observer_output.exists():
            raise SystemExit(f"refusing existing observer output: {observer_output}")
    expected = json.loads((package / "expected.json").read_text())

    verify(frontend, args.frontend_sha256)
    verify(FIRMWARE, PINS["firmware.bin"])
    verify(FIRMWARE_ELF, PINS["firmware.elf"])
    verify(BACKEND, PINS["flexe-vdp.so"])
    verify(package / "wolf3d.vdpl", PINS["wolf3d.vdpl"])
    for relative, item in expected["files"].items():
        verify(package / relative, item["sha256"])

    ensure_stopped(profile)
    retire_verified_profile_identity(profile)
    canonical = load_canonical()
    sdcard = canonical.link_shared_runtime(profile, FAB_RUNTIME)
    canonical.replace_symlink(profile / "fab-agon-emulator.bin", frontend)
    shutil.copyfile(BACKEND, profile / "flexe-vdp.so")
    shutil.copyfile(FIRMWARE, profile / "esp32-firmware.bin")
    shutil.copyfile(FIRMWARE_ELF, profile / "esp32-firmware.elf")
    (profile / ".bespoke-vdp-profile").write_text("flexe-vdp.so\n")

    app = sdcard / "wolf3d"
    canonical.replace_tree(package, app)
    (sdcard / "autoexec.txt").write_bytes(
        b"SET KEYBOARD 1\r\n"
        b"cd /wolf3d\r\n"
        b"load wolf3d.bin\r\n"
        b"run\r\n"
    )
    canonical.write_profile_launcher(profile, strict_bespoke=True)
    launcher = profile / "fab-agon-emulator"
    script = launcher.read_text()
    environment = """
export AGON_FLEXE_FIRMWARE="$profile_dir/esp32-firmware.bin"
export AGON_FLEXE_ELF="$profile_dir/esp32-firmware.elf"
export AGON_FLEXE_ENGINE="${AGON_FLEXE_ENGINE:-jit}"
export AGON_FLEXE_ARTIFACTS="$profile_dir/last-run"
mkdir -p "$AGON_FLEXE_ARTIFACTS"
"""
    if observer_output is not None:
        environment += (
            f'export FLEXE_UART_OBSERVER_OUTPUT="{observer_output}"\n'
        )
    if script.count("\nvdp_name=") != 1:
        raise SystemExit("canonical launcher has no unique VDP selection point")
    launcher.write_text(script.replace("\nvdp_name=", environment + "\nvdp_name=", 1))
    launcher.chmod(0o755)
    canonical.name_flexe_profile(profile)

    inputs = [
        "flexe-agon-emulator.bin", "flexe-vdp.so", "esp32-firmware.bin",
        "esp32-firmware.elf", "mos_platform.bin", "mos_platform.map",
        "sdcard/autoexec.txt",
    ]
    inputs.extend(
        str(path.relative_to(profile))
        for path in sorted(app.rglob("*")) if path.is_file()
    )
    (profile / ".runtime.sha256").write_text("".join(
        f"{sha(profile / name)}  {name}\n" for name in inputs
    ))
    subprocess.run(
        ["sha256sum", "--check", "--status", ".runtime.sha256"],
        cwd=profile, check=True,
    )
    ensure_stopped(profile)
    launcher = profile / "flexe-agon-emulator"
    if not launcher.is_file() or not os.access(launcher, os.X_OK):
        raise SystemExit(f"missing launcher: {launcher}")
    receipt = {
        "scope": "stopped complete Wolf3DOrig production direct-row VDPlet profile",
        "profile": str(profile),
        "launcher": str(launcher),
        "stopped": True,
        "application_sha256": sha(app / "wolf3d.bin"),
        "module_sha256": sha(app / "wolf3d.vdpl"),
        "frontend_sha256": sha(frontend),
        "mos_sha256": sha(profile / "mos_platform.bin"),
        "mos_map_sha256": sha(profile / "mos_platform.map"),
        "firmware_sha256": sha(profile / "esp32-firmware.bin"),
        "backend_sha256": sha(profile / "flexe-vdp.so"),
        "payload_files": len(expected["files"]),
        "observer_enabled": observer_output is not None,
        "observer_output": str(observer_output) if observer_output else None,
        "GUI_launched": False,
    }
    (profile / "profile.json").write_text(json.dumps(receipt, indent=2) + "\n")
    print(json.dumps(receipt, indent=2))


if __name__ == "__main__":
    main()
